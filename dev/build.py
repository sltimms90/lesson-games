"""Run after every edit to app/index.html:  python3 dev/build.py
Stamps the Content-Security-Policy with the hash of the app's one inline script (so injected inline code,
e.g. an onerror= attribute, can't run) and copies the app over the student page (index.html)."""
import base64, hashlib, os, re, sys
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
p = os.path.join(ROOT, "app", "index.html"); s = open(p, encoding="utf-8").read()
# The build id (APP_B): a hash of the script with the id blanked, so every change to the app gets a new one. Live
# messages and presence carry it, so a class-link page older than the teacher's app can tell and reload itself.
assert len(re.findall(r'var APP_B = "[0-9a-f]*";', s)) == 1, "expected one var APP_B"
s = re.sub(r'var APP_B = "[0-9a-f]*";', 'var APP_B = "";', s)
b0 = re.findall(r"<script>(.*?)</script>", s, re.S)[0]
bid = hashlib.sha256(b0.encode("utf-8")).hexdigest()[:10]
s = s.replace('var APP_B = "";', 'var APP_B = "%s";' % bid, 1)
scripts = re.findall(r"<script>(.*?)</script>", s, re.S)
assert len(scripts) == 1, "expected exactly one inline <script>, found %d" % len(scripts)
h = base64.b64encode(hashlib.sha256(scripts[0].encode("utf-8")).digest()).decode()
csp = "script-src 'self' 'sha256-%s'; object-src 'none'; base-uri 'none'" % h
tag = '<meta http-equiv="Content-Security-Policy" content="%s">' % csp
if re.search(r'<meta http-equiv="Content-Security-Policy"[^>]*>', s): s = re.sub(r'<meta http-equiv="Content-Security-Policy"[^>]*>', tag, s)
else: s = s.replace('<meta charset="utf-8">', '<meta charset="utf-8">\n' + tag, 1); assert tag in s
open(p, "w", encoding="utf-8").write(s)
open(os.path.join(ROOT, "index.html"), "w", encoding="utf-8").write(s)
print("build %s · CSP sha256-%s · app/index.html copied to index.html" % (bid, h))

# Showcase plans (27 Nov): dev/showcase/plans/<docId>.html → dev/showcase/plans.json (what the tests serve) and
# dev/sql/showcase_plans.sql. Run that file in the Supabase SQL editor after changing a plan: it loads private.showcase_plans,
# which plan-doc reads through rpc showcase_plan for Sam and guests; its last query lists each plan's md5 (compare plans.json).
import glob, hashlib, json
sc = {}
for f in sorted(glob.glob(os.path.join(ROOT, "dev", "showcase", "plans", "showcase-*.html"))):
    did = os.path.basename(f)[:-5]; m = re.match(r"showcase-([a-z-]+)-lp(\d+)-plan$", did)
    assert m and re.match(r"^[A-Za-z0-9_-]{20,128}$", did), "bad showcase plan name " + did
    who = m.group(1)
    sc[did] = {"name": "LP%s_%s_plan (demo).docx" % (m.group(2), "_".join(w.title() for w in who.split("-"))),
               "folderId": "showcase-folder-" + who, "html": open(f, encoding="utf-8").read().strip()}
with open(os.path.join(ROOT, "dev", "showcase", "plans.json"), "w", encoding="utf-8", newline="\n") as fh:
    fh.write(json.dumps({k: dict(v, md5=hashlib.md5(v["html"].encode("utf-8")).hexdigest()) for k, v in sc.items()}, ensure_ascii=False, indent=1, sort_keys=True) + "\n")
sql = ["-- Generated by dev/build.py from dev/showcase/plans/: don't edit. Loads the showcase plans plan-doc serves (27 Nov).",
       "delete from private.showcase_plans where doc_id not in (%s);" % ", ".join("'%s'" % k for k in sorted(sc))]
for k in sorted(sc):
    v = sc[k]; assert "$plan$" not in v["html"]
    sql.append("insert into private.showcase_plans (doc_id, name, folder_id, html) values ('%s', '%s', '%s', $plan$%s$plan$)\n  on conflict (doc_id) do update set name = excluded.name, folder_id = excluded.folder_id, html = excluded.html, updated_at = now();" % (k, v["name"], v["folderId"], v["html"]))
sql.append("select doc_id, md5(html) from private.showcase_plans order by doc_id;")
with open(os.path.join(ROOT, "dev", "sql", "showcase_plans.sql"), "w", encoding="utf-8", newline="\n") as fh:
    fh.write("\n".join(sql) + "\n")
print("showcase plans: %d -> dev/showcase/plans.json and dev/sql/showcase_plans.sql" % len(sc))
